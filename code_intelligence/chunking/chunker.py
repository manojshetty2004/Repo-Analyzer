from pathlib import Path

from code_intelligence.models import (
    RepositoryCodeModel,
    ModuleInfo,
    ClassInfo,
    FunctionInfo,
)

from code_intelligence.chunking.models import CodeChunk

class CodeChunker:
    def __init__(self, repository_name: str = "default"):
        self.repository_name = repository_name

    def build_chunks(
        self,
        repository: RepositoryCodeModel
    )->list[CodeChunk]:
        chunks: list[CodeChunk]=[]

        for module in repository.modules:
            chunks.extend(self._chunk_module(module))
        return chunks
    
    def _chunk_module(self,module:ModuleInfo)->list[CodeChunk]:
        chunks: list[CodeChunk] = []

        for cls in module.classes:
            chunks.append(self._build_class_chunk(module,cls))
        for func in module.functions:
            chunks.append(self._build_function_chunk(module,func))

        if not module.classes and not module.functions:
            chunks.append(self._build_module_chunk(module))
        
        return chunks

    def _build_class_chunk(self,
    module:ModuleInfo,
    cls:ClassInfo)->CodeChunk:
        return CodeChunk(
            id=f"{module.path}:{cls.qualified_name}",
            repository=self.repository_name,
            module_path=Path(module.path),
            symbol_name=cls.qualified_name,
            symbol_type="class",
            start_line=cls.start_line,
            end_line=cls.end_line,
            content=self._extract_class_text(cls),
        )

        
    def _build_function_chunk(
        self,
        module: ModuleInfo,
        function: FunctionInfo,
    ) -> CodeChunk:

        return CodeChunk(
            id=f"{module.path}:{function.qualified_name}",
            repository=self.repository_name,
            module_path=Path(module.path),
            symbol_name=function.qualified_name,
            symbol_type="function",
            start_line=function.start_line,
            end_line=function.end_line,
            content=self._extract_function_text(function),
        )

    def _build_module_chunk(
        self,
        module: ModuleInfo,
    ) -> CodeChunk:

        return CodeChunk(
            id=f"{module.path}:module",
            repository=self.repository_name,
            module_path=Path(module.path),
            symbol_name=module.path.stem,
            symbol_type="module",
            start_line=1,
            end_line=1,
            content=f"Module: {module.path.stem}",
        )

    def _extract_function_text(
        self,
        function: FunctionInfo,
    ) -> str:

        if getattr(function, "source_code", None):
            return function.source_code

        lines = [
            f"Function: {function.qualified_name}",
        ]

        if function.docstring:
            lines.append(function.docstring)

        if function.called_functions:
            lines.append(
                "Calls: " + ", ".join(function.called_functions)
            )

        return "\n".join(lines)


    def _extract_class_text(
        self,
        cls: ClassInfo,
    ) -> str:

        if getattr(cls, "source_code", None):
            return cls.source_code

        lines = [
            f"Class: {cls.qualified_name}",
        ]

        if cls.docstring:
            lines.append(cls.docstring)

        if cls.base_classes:
            lines.append(
                "Inherits: " + ", ".join(cls.base_classes)
            )

        if cls.methods:
            lines.append(
                "Methods: "
                + ", ".join(
                    method.name
                    for method in cls.methods
                )
            )

        return "\n".join(lines)


Chunker = CodeChunker

        















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































