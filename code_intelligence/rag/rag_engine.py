from code_intelligence.llm.base import LLMProvider
from code_intelligence.context.context_builder import ContextBuilder
from code_intelligence.search.repository_search import RepositorySearchService
from code_intelligence.rag.graph_context_builder import (
    GraphContextBuilder,
)
from code_intelligence.rag.prompt_builder import (
    PromptBuilder,
)
from code_intelligence.routing.intent_router import IntentRouter
from code_intelligence.routing.intent import Intent
from code_intelligence.analysis.repository_analysis_service import (
    RepositoryAnalysisService,
)
from code_intelligence.cli.formatter import ReportFormatter
from code_intelligence.memory.conversation_memory import ConversationMemory


class RagEngine:
    """
    Answers user questions using code context, relationships, and conversation memory,
    routing analytics queries to static reports where appropriate.
    """

    def __init__(
        self,
        llm_provider: LLMProvider,
        search_service: RepositorySearchService,
        context_builder: ContextBuilder,
        graph_context_builder: GraphContextBuilder,
        prompt_builder: PromptBuilder,
        router: IntentRouter,
        analysis: RepositoryAnalysisService,
        memory: ConversationMemory = None,
    ):
        self._llm_provider = llm_provider
        self._search_service = search_service
        self._context_builder = context_builder
        self._graph_context_builder = graph_context_builder
        self._prompt_builder = prompt_builder
        self._router = router
        self._analysis = analysis
        self._memory = memory if memory is not None else ConversationMemory()

    def answer(self, question: str) -> str:
        """
        Answers a question about the indexed repository.

        Parameters
        ----------
        question : str
            User's natural language question.

        Returns
        -------
        str
            Answer generated by the LLM or report formatter.
        """
        question = question.strip()
        if not question:
            raise ValueError("Question cannot be empty.")

        intent = self._router.route(question)

        if intent != Intent.RAG:
            try:
                report = self._analysis.last_report()
            except RuntimeError:
                return "The repository has not been analyzed yet. Please index/analyze the repository first."

            if report is None:
                return "The repository has not been analyzed yet. Please index/analyze the repository first."

            report_text = ""
            if intent == Intent.STATISTICS:
                report_text = ReportFormatter.statistics(report)
            elif intent == Intent.ARCHITECTURE:
                report_text = ReportFormatter.architecture(report)
            elif intent == Intent.COMPLEXITY:
                report_text = ReportFormatter.complexity(report)
            elif intent == Intent.COUPLING:
                report_text = ReportFormatter.coupling(report)
            elif intent == Intent.DEAD_CODE:
                report_text = ReportFormatter.dead_code(report)
            elif intent == Intent.DUPLICATES:
                report_text = ReportFormatter.duplicates(report)
            elif intent == Intent.CIRCULAR:
                report_text = ReportFormatter.circular(report)

            if intent == Intent.STATISTICS:
                return report_text

            prompt = (
                f"You are an expert AI Software Engineering Assistant.\n"
                f"Here is the static analysis report for the repository:\n"
                f"\"\"\"\n{report_text}\n\"\"\"\n\n"
                f"The user asked: \"{question}\"\n"
                f"Please explain these analysis results in detail in natural language, highlight key insights, and suggest concrete next steps."
            )
            return self._llm_provider.generate(prompt)

        # Step 1: Retrieve relevant code chunks
        search_results = self._search_service.search(question)

        # Step 2: Handle no search results
        if not search_results:
            return (
                "I couldn't find any relevant code in the indexed repository "
                "to answer your question."
            )

        # Step 3: Build contexts
        repository_context = self._context_builder.build(
            search_results,
        )

        graph_context = self._graph_context_builder.build(
            search_results,
        )

        conversation_context = self._memory.build_context()

        # Step 4: Build prompt
        prompt = self._prompt_builder.build(
            question=question,
            repository_context=repository_context,
            graph_context=graph_context,
            conversation_context=conversation_context,
        )

        # Step 5: Generate answer
        answer = self._llm_provider.generate(prompt)

        # Save turn to memory
        self._memory.add(question, answer)

        return answer